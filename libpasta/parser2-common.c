#include "parser.h"

#include <stdlib.h>

expr2_t *
expression_new(expr2_type_t type)
{
	expr2_t *expr = (expr2_t *) malloc(sizeof(expr2_t));
	if (expr != NULL) {
		expr->type = type;
	}
	return expr;
}
